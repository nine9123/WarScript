using System;
using System.IO;
using NUnit.Framework;
using Tests.Golden;
using WarScript.Audit;

namespace Tests
{
    /// <summary>
    /// Runs the suite with auditing on (v2 plan T0.8) when the environment
    /// variable <c>WARSCRIPT_AUDIT_REPORT</c> names an output file:
    ///
    /// <code>
    ///   WARSCRIPT_AUDIT_REPORT=$PWD/Documentation~/migration/audit-tests.md \
    ///     dotnet test "Headless~/Tests/WarScript.Tests.csproj"
    /// </code>
    ///
    /// Every <see cref="TestHelper.Run"/> and the source-mode,
    /// invariant-culture run of every golden report into one
    /// <see cref="AuditReport"/>, written as Markdown when the suite ends.
    /// Tests that build their own <c>WarScriptLanguage</c> are not audited,
    /// nor are '# isolate' goldens (they run in a child process).
    /// </summary>
    [SetUpFixture]
    public class AuditSuite
    {
        internal const string Variable = "WARSCRIPT_AUDIT_REPORT";

        private AuditReport _report;
        private string _path;

        [OneTimeSetUp]
        public void Start()
        {
            _path = Environment.GetEnvironmentVariable(Variable);
            if (string.IsNullOrEmpty(_path)) return;
            _report = new AuditReport();
            TestHelper.SuiteAudit = _report;
            GoldenRun.Audit = _report;
        }

        [OneTimeTearDown]
        public void Finish()
        {
            if (_report == null) return;
            TestHelper.SuiteAudit = null;
            GoldenRun.Audit = null;

            var preamble =
                "Generated by the test suite with auditing on (v2 plan T0.8, section 8.1):\n\n" +
                "```\n" + Variable + "=$PWD/Documentation~/migration/audit-tests.md dotnet test \"Headless~/Tests/WarScript.Tests.csproj\"\n```\n\n" +
                "Covered: every `TestHelper.Run`/`RunFile` (site `<fixture>.<test>: <script>:<line>`) and the source-mode, " +
                "invariant-culture run of every golden (site `Golden~/<file>:<line>`). Not covered: tests that build their own " +
                "`WarScriptLanguage`, and `# isolate` goldens. The deliberate examples in `AuditTests` override the sink and are " +
                "not included. v1 records line 0 for many expression instructions (T1.10); an event there is reported at the line " +
                "of the next instruction that has one, normally its statement.\n\n" +
                "Each section lists the sites of one kind with the functions they ran in, the number of events and the first " +
                "event's values. Plan 8.3 step 4 reviews this together with the game-session reports and the migration tool's report.\n\n";
            var markdown = _report.ToMarkdown("WarScript audit: test suite");
            var firstBreak = markdown.IndexOf("\n\n", StringComparison.Ordinal) + 2;
            File.WriteAllText(_path, markdown.Substring(0, firstBreak) + preamble + markdown.Substring(firstBreak));
        }
    }
}
